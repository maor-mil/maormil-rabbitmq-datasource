const amqp10DialTimeout = 15 * time.Second

// ErrAMQP10Unsupported is returned when the broker is older than RabbitMQ 4.0, which introduced the native
// AMQP 1.0 support (addresses and management) that queue consumption relies on.
var ErrAMQP10Unsupported = errors.New("consuming queues requires RabbitMQ 4.0 or later (native AMQP 1.0)")

// amqp10Address is the AMQP 1.0 address: no credentials (they go through SASL) and the vhost in the path,
// path-escaped (the client takes the vhost from the decoded path).
func amqp10Address(options *RabbitMQStreamOptions) string {
	scheme := "amqp"
	if options.IsTLS {
		scheme = "amqps"
	}
	return scheme + "://" + net.JoinHostPort(options.Host, strconv.Itoa(options.AmqpPort)) + "/" + url.PathEscape(options.VHost)
}

func amqp10SASL(options *RabbitMQStreamOptions) amqp.SASLType {
	if options.SASLMechanism == SASLMechanismExternal {
		return amqp.SASLTypeExternal("")
	}
	return amqp.SASLTypePlain(options.User, options.Password)
}

// ConsumeQueue consumes a classic or quorum queue over AMQP 1.0 and calls handle with each message body until
// ctx is done (returns nil) or the connection fails (returns the error, so Grafana retries the stream).
//
// Each call uses its own connection: in tap mode the temporary queue is exclusive to that connection, so the
// broker deletes it as soon as the panel stops streaming. The library's own reconnect logic is disabled —
// Grafana restarts the stream with a backoff instead.
func (client *RabbitMQStreamClient) ConsumeQueue(ctx context.Context, source Source, handle func(body []byte)) error {
	options := client.RabbitMQOptions
	if err := validateSASLMechanism(options.SASLMechanism); err != nil {
		return err
	}
	tlsConfig, err := buildTLSConfig(options)
	if err != nil {
		return err
	}

	dialCtx, cancel := context.WithTimeout(ctx, amqp10DialTimeout)
	defer cancel()
	conn, err := rmq.Dial(dialCtx, amqp10Address(options), &rmq.AmqpConnOptions{
		ContainerID:           "grafana-maormil-rabbitmq-datasource",
		SASLType:              amqp10SASL(options),
		TLSConfig:             tlsConfig,
		RecoveryConfiguration: &rmq.RecoveryConfiguration{ActiveRecovery: false},
	})
	if err != nil {
		return fmt.Errorf("AMQP 1.0 connection failed (%w); consuming queues requires RabbitMQ 4.0 or later", err)
	}
	defer func() {
		closeCtx, closeCancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer closeCancel()
		if err := conn.Close(closeCtx); err != nil {
			log.DefaultLogger.Debug("Closing the AMQP 1.0 connection failed", "error", err)
		}
	}()

	if err := requireRabbitMQ4(conn.Properties()); err != nil {
		return err
	}

	queue, settle, err := prepareQueue(ctx, conn, source)
	if err != nil {
		return err
	}
	consumer, err := conn.NewConsumer(ctx, queue, &rmq.ConsumerOptions{SettleStrategy: settle})
	if err != nil {
		return fmt.Errorf("consuming queue %q failed: %w", queue, err)
	}
	defer func() { _ = consumer.Close(context.Background()) }()
	log.DefaultLogger.Debug("Consuming queue over AMQP 1.0", "queue", queue, "mode", source.QueueMode)

	for {
		delivery, err := consumer.Receive(ctx)
		if err != nil {
			if ctx.Err() != nil {
				return nil
			}
			return fmt.Errorf("receiving from queue %q failed: %w", queue, err)
		}
		message := delivery.Message()
		if body, ok := MessageBody(message.Data, message.Value); ok {
			handle(body)
		} else {
			log.DefaultLogger.Warn("Skipping message without a supported body", "queue", queue, "bodyType", fmt.Sprintf("%T", message.Value))
		}
		if settle == rmq.ExplicitSettle {
			// Accept only after handing the message over (at-least-once for the destructive mode).
			if err := delivery.Accept(ctx); err != nil && ctx.Err() == nil {
				return fmt.Errorf("acknowledging a message from queue %q failed: %w", queue, err)
			}
		}
	}
}

// prepareQueue returns the queue to consume and how deliveries are settled. In tap mode it declares a
// server-named, exclusive, auto-delete queue and binds it to the exchange.
func prepareQueue(ctx context.Context, conn *rmq.AmqpConnection, source Source) (string, rmq.ConsumerSettleStrategy, error) {
	if source.QueueMode != QueueModeTap {
		return source.Queue, rmq.ExplicitSettle, nil
	}
	management := conn.Management()
	info, err := management.DeclareQueue(ctx, &rmq.AutoGeneratedQueueSpecification{IsAutoDelete: true, IsExclusive: true})
	if err != nil {
		return "", 0, fmt.Errorf("declaring the temporary tap queue failed: %w", err)
	}
	if _, err := management.Bind(ctx, &rmq.ExchangeToQueueBindingSpecification{
		SourceExchange:   source.Exchange,
		DestinationQueue: info.Name(),
		BindingKey:       source.RoutingKey,
	}); err != nil {
		return "", 0, fmt.Errorf("binding the tap queue to exchange %q failed (does the exchange exist?): %w", source.Exchange, err)
	}
	// The tap queue only holds copies, so there is nothing to acknowledge.
	return info.Name(), rmq.PreSettled, nil
}

// requireRabbitMQ4 checks the broker version announced in the AMQP 1.0 connection properties.
func requireRabbitMQ4(properties map[string]any) error {
	version, _ := properties["version"].(string)
	if version == "" {
		return nil // not announced: let the broker reject what it does not support
	}
	major, err := strconv.Atoi(strings.SplitN(version, ".", 2)[0])
	if err == nil && major < 4 {
		return fmt.Errorf("%w; the broker runs RabbitMQ %s", ErrAMQP10Unsupported, version)
	}
	return nil
}
